async def test_integridade_on_update_cascade(banco: BancoDeTeste) -> None:
    engine = motor(banco.url_dono)
    async with AsyncSession(engine) as session:
        # Permite update da coluna identity para testar o ON UPDATE CASCADE
        await session.execute(
            text("ALTER TABLE unidade_saude ALTER COLUMN idunidade SET GENERATED BY DEFAULT")
        )
        await session.commit()

        # Cria perfil e unidade
        perfil_repo = SqlPerfilRepository(session)
        p = await perfil_repo.add(Perfil(nome_perfil="Perfil Cascade", permissoes="adm"))
        unidade_repo = SqlUnidadeSaudeRepository(session)
        u = await unidade_repo.add(
            UnidadeSaude(
                codigo_cnes="9999001",
                nome="Unidade Cascade",
                tipo="UBS",
                endereco="Rua Teste, 100",
                cep="50000000",
                distrito_sanitario="Centro",
                status="Ativa",
            )
        )
        usuario_repo = SqlUsuarioRepository(session)
        usr = await usuario_repo.add(
            Usuario(
                nome="Usuario Cascade",
                email="cascade@sauderecife.pe.gov.br",
                senha_hash=VALID_HASH,
                id_perfil=p.id_perfil,  # type: ignore[arg-type]
                id_unidade=u.id_unidade,
            )
        )
        equip_repo = SqlEquipamentoRepository(session)
        eq = await equip_repo.add(
            Equipamento(
                nome="Equip Cascade",
                tipo="Respirador",
                quantidade=2,
                id_unidade=u.id_unidade,
            )
        )
        await session.commit()

        # Atualiza a PK da unidade
        id_antigo = u.id_unidade
        id_novo = id_antigo + 5000  # type: ignore[operator]
        await session.execute(
            text("UPDATE unidade_saude SET idunidade = :novo WHERE idunidade = :antigo"),
            {"novo": id_novo, "antigo": id_antigo},
        )
        await session.commit()

        # Verifica que o usuario e o equipamento foram atualizados em cascata
        usr_atualizado = await usuario_repo.get_by_id(usr.id_usuario)  # type: ignore[arg-type]
        assert usr_atualizado is not None
        assert usr_atualizado.id_unidade == id_novo

        eq_atualizado = await equip_repo.get_by_id(eq.id_equipamento)  # type: ignore[arg-type]
        assert eq_atualizado is not None
        assert eq_atualizado.id_unidade == id_novo

    await engine.dispose()


