async def test_migracao_etapa2_cria_todas_as_tabelas(banco: BancoDeTeste) -> None:
    engine = motor(banco.url_dono)
    async with engine.connect() as conn:
        for tbl in ("perfil", "unidade_saude", "usuario", "equipamento", "alteracao"):
            result = await conn.execute(
                text(
                    "SELECT EXISTS ("
                    "  SELECT FROM information_schema.tables "
                    "  WHERE table_schema = 'public' AND table_name = :t"
                    ");"
                ),
                {"t": tbl},
            )
            assert result.scalar() is True, f"Tabela {tbl} não foi criada!"
    await engine.dispose()


