-- Objetivo: índice GIN de trigramas sobre o nome normalizado, para a busca por trecho do nome.
-- Justificativa: a busca por texto livre acha o termo em qualquer parte do nome, sem acento nem
--   caixa (006/R2.2), e precisa responder em menos de 3 s com 1.000 unidades (006/R2.7). O
--   `ILIKE '%termo%'` não usa B-tree; com `gin_trgm_ops` (extensão `pg_trgm`) usa este índice.
--   Fica sobre a coluna gerada, então a busca e a unicidade usam a mesma normalização (011/R5.2).
-- Plano (011/R1.4; revisão do /implement-spec): Sem uso comprovado com o volume de demonstração.
--   (1.000 unidades com CNES, 3.000 serviços e a trilha correspondente, semeados pelo dono do
--   banco) e depois de ANALYZE, `EXPLAIN (COSTS OFF)` da consulta `search_health_units.sql` com texto livre,
--   pelo login da API, sem forçar nada (`enable_seqscan` no padrão). Teste que repete a prova:
--   `tests/integration/db/test_indices.py -m slow`.
--   Plano (trecho):
--     ->  Seq Scan on health_units u
--           Filter: ((name_normalized ~~* '%<termo normalizado>%'::text)
--                    OR ((cnes)::text ~~ '%<termo>%'::text))
--   Com 1.000 unidades a tabela ocupa poucas páginas e o planejador prefere lê-la inteira, mesmo
--   numa consulta só com o `ILIKE` do nome; na consulta da busca, o `OR cnes LIKE` também não
--   tem índice que o atenda. O índice fica para volumes maiores; registrado em "Perguntas em
--   aberto" da 011 (R1.4).
-- Uso: busca da 006 (`name_normalized ILIKE '%' || fn_normalize_name(:q) || '%'`, com
--   `similarity` para ordenar).
-- Requisitos: 006/R2.2, 006/R2.7, 011/R5.2
CREATE INDEX ix_health_units_name_normalized_trgm
    ON health_units USING gin (name_normalized gin_trgm_ops);
