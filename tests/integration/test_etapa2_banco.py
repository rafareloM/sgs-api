async def test_check_constraints_rejeitam_violacoes_no_banco(banco: BancoDeTeste) -> None:
    engine = motor(banco.url_dono)
    insert_prefix = (
        "INSERT INTO unidade_saude "
        "(codigocnes, nome, tipo, endereco, cep, distritosanitario, status) "
    )

    # CNES com 6 dígitos (inválido)
    with pytest.raises(exc.IntegrityError):
        async with engine.begin() as conn:
            await conn.execute(
                text(
                    insert_prefix
                    + "VALUES ('123456', 'UBS Inv', 'UBS', 'Rua X', '50010100', 'Centro', 'Ativa')"
                )
            )

    # CEP com 7 dígitos (inválido)
    with pytest.raises(exc.IntegrityError):
        async with engine.begin() as conn:
            await conn.execute(
                text(
                    insert_prefix
                    + "VALUES ('1234567', 'UBS Inv', 'UBS', 'Rua X', '5001010', 'Centro', 'Ativa')"
                )
            )

    # Tipo de unidade inválido
    with pytest.raises(exc.IntegrityError):
        async with engine.begin() as conn:
            await conn.execute(
                text(
                    insert_prefix
                    + "VALUES ('1234567', 'UBS Inv', 'Inv', 'Rua X', '50010100', 'Centro', 'Ativa')"
                )
            )

    # Equipamento com quantidade acima do limite de 5000
    with pytest.raises(exc.IntegrityError):
        async with engine.begin() as conn:
            await conn.execute(
                text(
                    "INSERT INTO equipamento (nome, tipo, quantidade, idunidade) "
                    "VALUES ('Balança', 'Balança', 5001, 1)"
                )
            )
    await engine.dispose()
